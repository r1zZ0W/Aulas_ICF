/**
 * Defines the time period covered by a generated reservation report.
 *
 * @author Ithera
 * @version 1.0
 */
public enum ReportPeriod {

    /** The calendar month immediately preceding the current month. */
    MES_ANTERIOR,

    /** The current calendar month up to today. */
    MES_EN_CURSO
}
